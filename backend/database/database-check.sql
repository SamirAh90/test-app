USE medborgatest_db;

CREATE TABLE IF NOT EXISTS subject_materials (
  id INT AUTO_INCREMENT PRIMARY KEY,
  subjectId INT NOT NULL UNIQUE,
  title VARCHAR(255) NOT NULL,
  introduction TEXT,
  body LONGTEXT NOT NULL,
  createdAt DATETIME NOT NULL DEFAULT CURRENT_TIMESTAMP,
  updatedAt DATETIME NOT NULL DEFAULT CURRENT_TIMESTAMP
    ON UPDATE CURRENT_TIMESTAMP,

  CONSTRAINT fk_subject_material_subject
    FOREIGN KEY (subjectId)
    REFERENCES subjects(id)
    ON DELETE CASCADE
);

CREATE TABLE IF NOT EXISTS subject_glossary (
  id INT AUTO_INCREMENT PRIMARY KEY,
  subjectId INT NOT NULL,
  word VARCHAR(255) NOT NULL,
  definition TEXT NOT NULL,
  displayOrder INT NOT NULL DEFAULT 0,
  createdAt DATETIME NOT NULL DEFAULT CURRENT_TIMESTAMP,
  updatedAt DATETIME NOT NULL DEFAULT CURRENT_TIMESTAMP
    ON UPDATE CURRENT_TIMESTAMP,

  CONSTRAINT fk_subject_glossary_subject
    FOREIGN KEY (subjectId)
    REFERENCES subjects(id)
    ON DELETE CASCADE
);

CREATE TABLE IF NOT EXISTS subject_sources (
  id INT AUTO_INCREMENT PRIMARY KEY,
  subjectId INT NOT NULL,
  title VARCHAR(255) NOT NULL,
  url VARCHAR(500) NOT NULL,
  displayOrder INT NOT NULL DEFAULT 0,
  createdAt DATETIME NOT NULL DEFAULT CURRENT_TIMESTAMP,
  updatedAt DATETIME NOT NULL DEFAULT CURRENT_TIMESTAMP
    ON UPDATE CURRENT_TIMESTAMP,

  CONSTRAINT fk_subject_source_subject
    FOREIGN KEY (subjectId)
    REFERENCES subjects(id)
    ON DELETE CASCADE
);